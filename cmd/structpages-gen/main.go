// Command structpages-gen writes the tables structpages reads in builds
// whose reflect package can't list or call methods: TinyGo's.
//
//	go tool structpages-gen [-test] [-tags tags] [packages]
//
// For each package (default ./...) that declares page types, standalone
// components or request-arg functions, it writes structpages_tables.go,
// built only under TinyGo or the structpages_tables build tag. With -test it
// also writes the tables for what the package's tests declare. Run it again
// whenever a page's methods change; a stale table fails at Mount.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	structpagesPath = "github.com/jackielii/structpages"
	tablesPath      = structpagesPath + "/tables"
	header          = "// Code generated by structpages-gen. DO NOT EDIT.\n"
	buildTag        = "//go:build tinygo || structpages_tables\n"
)

// pageMethods are the methods that make a struct a page on their own.
var pageMethods = []string{"Page", "ServeHTTP", "Middlewares", "RequestArgs", "Init"}

func main() {
	test := flag.Bool("test", false, "also write tables for what the packages' _test.go files declare")
	tags := flag.String("tags", "", "build tags to load the packages with")
	flag.Usage = func() {
		fmt.Fprintf(os.Stderr, "usage: structpages-gen [-test] [-tags tags] [packages]\n")
		flag.PrintDefaults()
	}
	flag.Parse()
	patterns := flag.Args()
	if len(patterns) == 0 {
		patterns = []string{"./..."}
	}
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedDeps | packages.NeedImports,
		Tests: *test,
	}
	if *tags != "" {
		cfg.BuildFlags = []string{"-tags=" + *tags}
	}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		fmt.Fprintln(os.Stderr, "structpages-gen:", err)
		os.Exit(2)
	}
	if packages.PrintErrors(pkgs) > 0 {
		os.Exit(2)
	}
	routed := routedTypes(pkgs)
	failed := false
	for _, p := range pkgs {
		files, out := coveredFiles(p)
		if files == nil {
			continue
		}
		g := &gen{pkg: p, files: files, routed: routed, inTest: p.ID != p.PkgPath}
		src, err := g.generate()
		if err != nil {
			fmt.Fprintf(os.Stderr, "structpages-gen: %s: %v\n", p.ID, err)
			failed = true
			continue
		}
		if err := write(out, src); err != nil {
			fmt.Fprintln(os.Stderr, "structpages-gen:", err)
			failed = true
		}
	}
	if failed {
		os.Exit(1)
	}
}

// coveredFiles returns the files of p whose declarations p's table covers,
// and the table's path: a package's own files, its _test.go files in the
// package's test variant, and an external test package's files.
func coveredFiles(p *packages.Package) (map[string]bool, string) {
	if p.PkgPath == tablesPath || strings.HasSuffix(p.ID, ".test") || len(p.GoFiles) == 0 {
		return nil, ""
	}
	inTest := p.ID != p.PkgPath // "pkg [pkg.test]" or "pkg_test [pkg.test]"
	if p.PkgPath == structpagesPath && !inTest {
		return nil, "" // the library declares no pages; its tests do
	}
	external := inTest && strings.HasSuffix(p.Name, "_test")
	files := map[string]bool{}
	for _, f := range p.GoFiles {
		if strings.HasSuffix(f, "_test.go") == inTest {
			files[f] = true
		}
	}
	if len(files) == 0 {
		return nil, ""
	}
	name := "structpages_tables.go"
	switch {
	case external:
		name = "structpages_tables_external_test.go"
	case inTest:
		name = "structpages_tables_test.go"
	}
	return files, filepath.Join(filepath.Dir(p.GoFiles[0]), name)
}

// routedTypes collects the named types of every route-tagged field in pkgs,
// by typeKey: pages, whatever else they declare. A package's test variant
// has its own type objects, so they are keyed by name.
func routedTypes(pkgs []*packages.Package) map[string]bool {
	routed := map[string]bool{}
	for _, p := range pkgs {
		for _, f := range p.Syntax {
			ast.Inspect(f, func(n ast.Node) bool {
				st, ok := n.(*ast.StructType)
				if !ok {
					return true
				}
				for _, field := range st.Fields.List {
					if field.Tag == nil || !hasRoute(field.Tag.Value) {
						continue
					}
					if tn := namedObj(p.TypesInfo.TypeOf(field.Type)); tn != nil && tn.Pkg() != nil {
						routed[typeKey(tn)] = true
					}
				}
				return true
			})
		}
	}
	return routed
}

func hasRoute(lit string) bool {
	tag, err := strconv.Unquote(lit)
	if err != nil {
		return false
	}
	_, ok := reflect.StructTag(tag).Lookup("route")
	return ok
}

func typeKey(tn *types.TypeName) string { return tn.Pkg().Path() + "." + tn.Name() }

// namedObj is t's type name, through a pointer.
func namedObj(t types.Type) *types.TypeName {
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	if n, ok := t.(*types.Named); ok {
		return n.Origin().Obj()
	}
	return nil
}

type gen struct {
	pkg    *packages.Package
	files  map[string]bool
	routed map[string]bool
	inTest bool

	imports   map[string]string // path → name
	names     map[string]bool   // names taken in the file
	funcTypes map[string]*types.Signature
	warnings  []string
}

func (g *gen) covered(pos token.Pos) bool {
	return g.files[g.pkg.Fset.Position(pos).Filename]
}

func (g *gen) warn(pos token.Pos, format string, args ...any) {
	g.warnings = append(g.warnings, fmt.Sprintf("%s: %s", g.pkg.Fset.Position(pos), fmt.Sprintf(format, args...)))
}

// pageType is one page type and its two method sets.
type pageType struct {
	obj            *types.TypeName
	value, pointer []method
}

type method struct {
	name     string
	sig      *types.Signature // with the receiver as its first parameter
	promoted bool             // reached through an autogenerated wrapper
	embedded bool             // promoted from an embedded field
}

func (g *gen) generate() ([]byte, error) {
	g.imports = map[string]string{}
	g.names = map[string]bool{}
	g.funcTypes = map[string]*types.Signature{}
	for _, name := range g.pkg.Types.Scope().Names() {
		g.names[name] = true
	}

	var pages []pageType
	var funcs []*types.Func
	for _, f := range g.pkg.Syntax {
		if !g.covered(f.Pos()) {
			continue
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				for _, s := range d.Specs {
					ts, ok := s.(*ast.TypeSpec)
					if !ok || ts.Assign.IsValid() {
						continue
					}
					tn, _ := g.pkg.TypesInfo.Defs[ts.Name].(*types.TypeName)
					if tn == nil || !g.isPage(tn) {
						continue
					}
					if ts.TypeParams != nil {
						g.warn(ts.Pos(), "generic type %s: tables builds can't list or call its methods", tn.Name())
						continue
					}
					if pt, ok := g.pageType(tn); ok {
						pages = append(pages, pt)
					}
				}
			case *ast.FuncDecl:
				fn, _ := g.pkg.TypesInfo.Defs[d.Name].(*types.Func)
				if fn == nil || d.Recv != nil || d.Type.TypeParams != nil {
					continue
				}
				sig := fn.Type().(*types.Signature)
				if sig.Results().Len() == 1 && isComponent(sig.Results().At(0).Type()) {
					funcs = append(funcs, fn)
				}
				if isRequestArg(sig) {
					g.addFuncType(sig, d.Pos())
				}
			}
		}
	}
	// Request-arg functions used anywhere in the covered files: literals,
	// method values and functions from other packages.
	for expr, tv := range g.pkg.TypesInfo.Types {
		if sig, ok := tv.Type.(*types.Signature); ok && g.covered(expr.Pos()) && isRequestArg(sig) {
			g.addFuncType(sig, expr.Pos())
		}
	}
	for _, w := range g.warnings {
		fmt.Fprintln(os.Stderr, "structpages-gen: warning:", w)
	}
	if len(pages) == 0 && len(funcs) == 0 && len(g.funcTypes) == 0 {
		return nil, nil
	}
	return g.file(pages, funcs)
}

// isPage reports whether tn, a struct type declared in the package, is a
// page: it has route-tagged fields, is the type of one, or declares a page
// method or a component. Tests build pages in more ways, so in test files
// every struct type with methods counts.
func (g *gen) isPage(tn *types.TypeName) bool {
	if g.routed[typeKey(tn)] {
		return true
	}
	st, ok := tn.Type().Underlying().(*types.Struct)
	if !ok {
		return false
	}
	if g.inTest && types.NewMethodSet(types.NewPointer(tn.Type())).Len() > 0 {
		return true
	}
	for i := range st.NumFields() {
		if _, ok := reflect.StructTag(st.Tag(i)).Lookup("route"); ok {
			return true
		}
	}
	ms := types.NewMethodSet(types.NewPointer(tn.Type()))
	for i := range ms.Len() {
		fn := ms.At(i).Obj().(*types.Func)
		if !fn.Exported() {
			continue
		}
		name := fn.Name()
		if slices.Contains(pageMethods, name) || strings.HasSuffix(name, "Props") {
			return true
		}
		sig := fn.Type().(*types.Signature)
		if sig.Results().Len() == 1 && isComponent(sig.Results().At(0).Type()) {
			return true
		}
	}
	return false
}

// pageType lists tn's methods on the value and the pointer type, as
// reflect would, and adds their function types. Its own unexported methods
// are listed too: reflect doesn't list them, but ID and RenderTarget.Is
// name them when a method expression is passed.
func (g *gen) pageType(tn *types.TypeName) (pageType, bool) {
	pt := pageType{obj: tn}
	for _, ptr := range []bool{false, true} {
		recv := tn.Type()
		if ptr {
			recv = types.NewPointer(recv)
		}
		ms := types.NewMethodSet(recv)
		var list []method
		for i := range ms.Len() {
			sel := ms.At(i)
			fn := sel.Obj().(*types.Func)
			embedded := len(sel.Index()) > 1
			if !fn.Exported() && (embedded || fn.Pkg() != g.pkg.Types) {
				continue
			}
			sig := fn.Type().(*types.Signature)
			_, ptrRecv := sig.Recv().Type().(*types.Pointer)
			m := method{
				name:     fn.Name(),
				sig:      withReceiver(recv, sig),
				embedded: embedded,
				// Through the pointer type, a method declared on the
				// value type is an autogenerated wrapper too.
				promoted: embedded || (ptr && !ptrRecv),
			}
			// structpages never calls a promoted method, so one whose type
			// can't be written here is listed without it.
			if why := g.unnameable(m.sig); why == "" {
				g.addFuncType(m.sig, tn.Pos())
			} else if !embedded {
				g.warn(tn.Pos(), "page type %s: method %s: %s", tn.Name(), fn.Name(), why)
				return pageType{}, false
			}
			list = append(list, m)
		}
		sort.Slice(list, func(i, j int) bool { return list[i].name < list[j].name })
		if ptr {
			pt.pointer = list
		} else {
			pt.value = list
		}
	}
	return pt, true
}

// withReceiver is sig with recv as its first parameter: a method
// expression's type.
func withReceiver(recv types.Type, sig *types.Signature) *types.Signature {
	params := []*types.Var{types.NewParam(token.NoPos, nil, "", recv)}
	for i := range sig.Params().Len() {
		params = append(params, types.NewParam(token.NoPos, nil, "", sig.Params().At(i).Type()))
	}
	return types.NewSignatureType(nil, nil, nil, types.NewTuple(params...), unnamed(sig.Results()), sig.Variadic())
}

func unnamed(t *types.Tuple) *types.Tuple {
	vs := make([]*types.Var, t.Len())
	for i := range vs {
		vs[i] = types.NewParam(token.NoPos, nil, "", t.At(i).Type())
	}
	return types.NewTuple(vs...)
}

func (g *gen) addFuncType(sig *types.Signature, pos token.Pos) {
	sig = types.NewSignatureType(nil, nil, nil, unnamed(sig.Params()), unnamed(sig.Results()), sig.Variadic())
	if why := g.unnameable(sig); why != "" {
		g.warn(pos, "function type %s: %s", types.TypeString(sig, nil), why)
		return
	}
	g.funcTypes[types.TypeString(sig, (*types.Package).Path)] = sig
}

// unnameable says why t can't be written in the generated file, or "".
func (g *gen) unnameable(t types.Type) string {
	switch t := t.(type) {
	case *types.Basic:
		return ""
	case *types.Named:
		obj := t.Obj()
		if obj.Pkg() != nil {
			if obj.Parent() != obj.Pkg().Scope() {
				return obj.Name() + " is declared inside a function"
			}
			if obj.Pkg() != g.pkg.Types && obj.Pkg().Path() != g.pkg.PkgPath && !obj.Exported() {
				return obj.Name() + " is unexported in " + obj.Pkg().Path()
			}
		}
		if t.TypeParams().Len() > 0 && t.TypeArgs().Len() == 0 {
			return obj.Name() + " is generic"
		}
		for i := range t.TypeArgs().Len() {
			if why := g.unnameable(t.TypeArgs().At(i)); why != "" {
				return why
			}
		}
		return ""
	case *types.Alias:
		return g.unnameable(types.Unalias(t))
	case *types.TypeParam:
		return "it uses type parameter " + t.Obj().Name()
	case *types.Pointer:
		return g.unnameable(t.Elem())
	case *types.Slice:
		return g.unnameable(t.Elem())
	case *types.Array:
		return g.unnameable(t.Elem())
	case *types.Chan:
		return g.unnameable(t.Elem())
	case *types.Map:
		if why := g.unnameable(t.Key()); why != "" {
			return why
		}
		return g.unnameable(t.Elem())
	case *types.Signature:
		for _, tup := range []*types.Tuple{t.Params(), t.Results()} {
			for i := range tup.Len() {
				if why := g.unnameable(tup.At(i).Type()); why != "" {
					return why
				}
			}
		}
		return ""
	case *types.Struct:
		for i := range t.NumFields() {
			f := t.Field(i)
			if !f.Exported() && f.Pkg() != g.pkg.Types {
				return "a struct type with unexported fields of another package"
			}
			if why := g.unnameable(f.Type()); why != "" {
				return why
			}
		}
		return ""
	case *types.Interface:
		for i := range t.NumExplicitMethods() {
			m := t.ExplicitMethod(i)
			if !m.Exported() && m.Pkg() != g.pkg.Types {
				return "an interface type with unexported methods of another package"
			}
			if why := g.unnameable(m.Type()); why != "" {
				return why
			}
		}
		for i := range t.NumEmbeddeds() {
			if why := g.unnameable(t.EmbeddedType(i)); why != "" {
				return why
			}
		}
		return ""
	}
	return fmt.Sprintf("unsupported type %s", t)
}

// isComponent reports whether t has Render(context.Context, io.Writer) error.
func isComponent(t types.Type) bool {
	obj, _, _ := types.LookupFieldOrMethod(t, true, nil, "Render")
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig := fn.Type().(*types.Signature)
	return sig.Params().Len() == 2 && sig.Results().Len() == 1 &&
		types.TypeString(sig.Params().At(0).Type(), nil) == "context.Context" &&
		types.TypeString(sig.Params().At(1).Type(), nil) == "io.Writer" &&
		types.TypeString(sig.Results().At(0).Type(), nil) == "error"
}

// isRequestArg reports whether sig is a request-arg provider's:
// func(*http.Request) (T, error) or func(*http.Request, *PageNode) (T, error).
func isRequestArg(sig *types.Signature) bool {
	if sig.TypeParams().Len() > 0 || sig.Variadic() || sig.Results().Len() != 2 ||
		types.TypeString(sig.Results().At(1).Type(), nil) != "error" {
		return false
	}
	ps := sig.Params()
	if ps.Len() != 1 && ps.Len() != 2 {
		return false
	}
	if types.TypeString(ps.At(0).Type(), nil) != "*net/http.Request" {
		return false
	}
	return ps.Len() == 1 || types.TypeString(ps.At(1).Type(), nil) == "*"+structpagesPath+".PageNode"
}

// qualifier names other packages' types by their imports in the generated
// file.
func (g *gen) qualifier(p *types.Package) string {
	if p == g.pkg.Types || p.Path() == g.pkg.PkgPath {
		return ""
	}
	return g.importName(p.Path(), p.Name())
}

func (g *gen) importName(path, name string) string {
	if n, ok := g.imports[path]; ok {
		return n
	}
	n := name
	for i := 2; g.names[n]; i++ {
		n = name + strconv.Itoa(i)
	}
	g.names[n] = true
	g.imports[path] = n
	return n
}

func (g *gen) typ(t types.Type) string { return types.TypeString(t, g.qualifier) }

func (g *gen) file(pages []pageType, funcs []*types.Func) ([]byte, error) {
	reflectName := g.importName("reflect", "reflect")
	tablesName := g.importName(tablesPath, "tables")
	var body bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&body, format, args...) }

	w("func init() {\n")
	if len(g.funcTypes) > 0 {
		keys := make([]string, 0, len(g.funcTypes))
		for k := range g.funcTypes {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		w("%s.AddFuncTypes(\n", tablesName)
		for _, k := range keys {
			g.funcType(w, reflectName, tablesName, g.funcTypes[k])
		}
		w(")\n")
	}
	sort.Slice(pages, func(i, j int) bool { return pages[i].obj.Name() < pages[j].obj.Name() })
	for _, pt := range pages {
		for _, ptr := range []bool{false, true} {
			list, recv := pt.value, pt.obj.Name()
			if ptr {
				list, recv = pt.pointer, "*"+recv
			}
			if len(list) == 0 {
				continue
			}
			w("%s.AddMethods(%s.TypeFor[%s](),\n", tablesName, reflectName, recv)
			for _, m := range list {
				expr := recv + "." + m.name
				if ptr {
					expr = "(" + recv + ")." + m.name
				}
				w("%s.Method{Name: %q, Expr: %s", tablesName, m.name, expr)
				if !m.embedded {
					// A method promoted through an embedded nil pointer
					// can't be bound on new(T); it is never a component.
					w(", Bound: new(%s).%s", pt.obj.Name(), m.name)
				}
				if m.promoted {
					w(", Promoted: true")
				}
				w("},\n")
			}
			w(")\n")
		}
	}
	if len(funcs) > 0 {
		sort.Slice(funcs, func(i, j int) bool { return funcs[i].Name() < funcs[j].Name() })
		path := g.pkg.PkgPath
		if g.pkg.Name == "main" {
			path = "main"
		}
		w("%s.AddFunctions(%q,\n", tablesName, path)
		for _, fn := range funcs {
			w("%s.Function{Name: %q, Func: %s},\n", tablesName, fn.Name(), fn.Name())
		}
		w(")\n")
	}
	w("}\n")

	var out bytes.Buffer
	out.WriteString(buildTag + "\n" + header + "\npackage " + g.pkg.Name + "\n\nimport (\n")
	var std, others []string
	for p := range g.imports {
		if strings.Contains(strings.Split(p, "/")[0], ".") {
			others = append(others, p)
		} else {
			std = append(std, p)
		}
	}
	sort.Strings(std)
	sort.Strings(others)
	for i, group := range [][]string{std, others} {
		if i > 0 && len(std) > 0 && len(others) > 0 {
			out.WriteString("\n")
		}
		for _, p := range group {
			if n := g.imports[p]; n != filepath.Base(p) {
				fmt.Fprintf(&out, "%s %q\n", n, p)
			} else {
				fmt.Fprintf(&out, "%q\n", p)
			}
		}
	}
	out.WriteString(")\n\n")
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the generated file: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

// funcType writes sig's table: its types and a call that converts the
// arguments and results as reflect.Value.Call does.
func (g *gen) funcType(w func(string, ...any), reflectName, tablesName string, sig *types.Signature) {
	ft := g.typ(sig)
	typeList := func(t *types.Tuple) string {
		var b strings.Builder
		for i := range t.Len() {
			fmt.Fprintf(&b, "%s.TypeFor[%s](), ", reflectName, g.typ(t.At(i).Type()))
		}
		return strings.TrimSuffix(b.String(), ", ")
	}
	params, results := sig.Params(), sig.Results()
	w("%s.FuncType{\n", tablesName)
	w("Type: %s.TypeFor[%s](),\n", reflectName, ft)
	w("In: []%s.Type{%s},\n", reflectName, typeList(params))
	w("Out: []%s.Type{%s},\n", reflectName, typeList(results))
	if sig.Variadic() {
		w("Variadic: true,\n")
	}
	w("Call: func(fn %s.Value, in []%s.Value) []%s.Value {\n", reflectName, reflectName, reflectName)
	var args []string
	n := params.Len()
	for i := range n {
		pt := params.At(i).Type()
		if sig.Variadic() && i == n-1 {
			elem := g.typ(pt.(*types.Slice).Elem())
			w("rest := make([]%s, len(in)-%d)\n", elem, n-1)
			w("for i, v := range in[%d:] {\nrest[i] = %s.Arg[%s](v)\n}\n", n-1, tablesName, elem)
			args = append(args, "rest...")
			continue
		}
		args = append(args, fmt.Sprintf("%s.Arg[%s](in[%d])", tablesName, g.typ(pt), i))
	}
	call := fmt.Sprintf("fn.Interface().(%s)(%s)", ft, strings.Join(args, ", "))
	if results.Len() == 0 {
		w("%s\nreturn nil\n", call)
	} else {
		var rs, vs []string
		for i := range results.Len() {
			rs = append(rs, "r"+strconv.Itoa(i))
			vs = append(vs, fmt.Sprintf("%s.Result(r%d)", tablesName, i))
		}
		w("%s := %s\n", strings.Join(rs, ", "), call)
		w("return []%s.Value{%s}\n", reflectName, strings.Join(vs, ", "))
	}
	w("},\n},\n")
}

// write writes src to path, or removes a generated file there when src is
// nil. It leaves a file it didn't write alone.
func write(path string, src []byte) error {
	old, err := os.ReadFile(path)
	if err == nil && !bytes.Contains(old, []byte(header)) {
		if src == nil {
			return nil
		}
		return fmt.Errorf("%s exists and was not written by structpages-gen", path)
	}
	if src == nil {
		if err == nil {
			return os.Remove(path)
		}
		return nil
	}
	if bytes.Equal(old, src) {
		return nil
	}
	return os.WriteFile(path, src, 0o644)
}
