// Package e2e tests an app end to end, and that it answers the same however
// it is built: with reflect, with generated code (-tags
// structpages_static), or under TinyGo.
//
// Crawl walks an app's http.Handler in-process from "/", following the links,
// forms and htmx attributes in each HTML response (sending htmx's request
// headers, so partials are covered), and compares every response with a file
// recorded from the dynamic build. It needs no sockets, so the same test
// runs all three ways; an example calls it from one test:
//
//	func TestE2E(t *testing.T) { e2e.Crawl(t, handler(), "testdata/e2e.generated.txt") }
//
// With -update (go test -update), Crawl writes the file instead of comparing
// with it. Record it from the dynamic build (no build tags), the reference
// the other two ways are compared with, and commit it: a change to it is a
// change in what the app answers. As -update is a flag of its own, go test
// doesn't cache the run, so it records every time.
//
// Bench times the requests in that file that only read (its GETs), Reads,
// in-process, one sub-benchmark each, so the three ways can be compared per
// request:
//
//	func BenchmarkE2E(b *testing.B) { e2e.Bench(b, handler(), "testdata/e2e.generated.txt") }
//
// Reads also gives them to a client timing the app as served.
package e2e

import (
	"bytes"
	"cmp"
	"flag"
	"fmt"
	"html"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
	"unicode/utf8"
)

// update makes Crawl record the responses instead of comparing with them.
var update = flag.Bool("update", false, "e2e: record the responses into the file instead of comparing with it")

// maxRequests stops a crawl that keeps finding new URLs.
const maxRequests = 500

const fileHeader = "# Generated by e2e.Crawl from the dynamic build, with go test -update. Do not edit.\n"

// request is one request the crawl makes: a link, a form, or an htmx
// attribute it found.
type request struct {
	method, path string
	htmx         bool
	target       string // sent as HX-Target: the id hx-target names
}

func (r request) String() string {
	s := r.method + " " + r.path
	switch {
	case r.target != "":
		s += " (htmx, target " + r.target + ")"
	case r.htmx:
		s += " (htmx)"
	}
	return s
}

// Crawl requests "/" and everything reachable from it through h, in order,
// and compares the responses with file.
func Crawl(t testing.TB, h http.Handler, file string) {
	t.Helper()
	var out bytes.Buffer
	out.WriteString(fileHeader)
	start := request{method: http.MethodGet, path: "/"}
	queue, seen := []request{start}, map[request]bool{start: true}
	add := func(r request) {
		if !seen[r] {
			seen[r] = true
			queue = append(queue, r)
		}
	}
	for n := 0; len(queue) > 0; n++ {
		if n == maxRequests {
			t.Fatalf("e2e: over %d requests; the app keeps producing new URLs", maxRequests)
		}
		req := queue[0]
		queue = queue[1:]
		rec := serve(h, req)
		ct, loc := rec.Header().Get("Content-Type"), rec.Header().Get("Location")
		fmt.Fprintf(&out, "\n### %s\n%d %s\n", req, rec.Code, ct)
		if loc != "" {
			fmt.Fprintf(&out, "Location: %s\n", loc)
		}
		body := rec.Body.String()
		out.WriteString(body)
		if !strings.HasSuffix(body, "\n") {
			out.WriteString("\n")
		}
		if p, ok := localPath(loc); ok {
			add(request{method: http.MethodGet, path: p})
		}
		if strings.HasPrefix(ct, "text/html") {
			for _, r := range links(body) {
				add(r)
			}
		}
	}
	compare(t, file, out.Bytes())
}

// Bench runs each GET recorded in file as a sub-benchmark named for it:
// requests that change the app (POST, DELETE, ...) would make every
// iteration different, so they are left out.
func Bench(b *testing.B, h http.Handler, file string) {
	b.Helper()
	reads, err := Reads(file)
	if err != nil {
		b.Fatal(err)
	}
	for _, r := range reads {
		b.Run(r.Name, func(b *testing.B) {
			b.ReportAllocs()
			for range b.N {
				serve(h, r.request)
			}
		})
	}
}

// Read is a request in a recording that only reads: a GET.
type Read struct {
	// Name is Bench's name for it: GET_items, or GET_items_htmx for an htmx
	// partial.
	Name string
	// Path is its path and query, and Header the request headers it is sent
	// with: htmx's, for a partial.
	Path   string
	Header http.Header
	request
}

// Reads returns the requests in file that only read (its GETs), in order:
// what Bench times.
func Reads(file string) ([]Read, error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return nil, fmt.Errorf("e2e: %w; record it first: go test -update", err)
	}
	var reads []Read
	for _, s := range sections(data) {
		line, _, _ := strings.Cut(s, "\n")
		req, ok := parseRequest(line)
		if !ok || req.method != http.MethodGet {
			continue
		}
		reads = append(reads, Read{Name: benchName(req), Path: req.path, Header: newRequest(req).Header, request: req})
	}
	return reads, nil
}

// parseRequest reads a request back from its String form.
func parseRequest(s string) (request, bool) {
	s, extra, _ := strings.Cut(s, " (")
	method, path, ok := strings.Cut(s, " ")
	if !ok {
		return request{}, false
	}
	r := request{method: method, path: path}
	if extra != "" {
		r.htmx = true
		if t, ok := strings.CutPrefix(strings.TrimSuffix(extra, ")"), "htmx, target "); ok {
			r.target = t
		}
	}
	return r, true
}

// benchName is a sub-benchmark name for r: no slashes, which nest names.
func benchName(r request) string {
	n := r.method + "_" + strings.ReplaceAll(strings.TrimPrefix(r.path, "/"), "/", "_")
	if r.htmx {
		n += "_htmx"
	}
	return n
}

func serve(h http.Handler, req request) *httptest.ResponseRecorder {
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, newRequest(req))
	return rec
}

// newRequest is req as an http.Request: a form sent empty, and htmx's
// headers for a partial.
func newRequest(req request) *http.Request {
	var r *http.Request
	switch req.method {
	case http.MethodPost, http.MethodPut, http.MethodPatch:
		// The crawl doesn't fill in forms: it sends them empty.
		r = httptest.NewRequest(req.method, req.path, strings.NewReader(""))
		r.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	default:
		r = httptest.NewRequest(req.method, req.path, http.NoBody)
	}
	if req.htmx {
		r.Header.Set("HX-Request", "true")
	}
	if req.target != "" {
		r.Header.Set("HX-Target", req.target)
	}
	return r
}

var (
	tagRe  = regexp.MustCompile(`<[a-zA-Z][^>]*>`)
	attrRe = regexp.MustCompile(`([a-zA-Z_:.-]+)\s*=\s*(?:"([^"]*)"|'([^']*)')`)
	verbs  = []string{"get", "post", "put", "patch", "delete"}
)

// links lists the requests the elements in body would make, in document
// order: href, a form's action and method, and htmx's hx-get, hx-post and
// the rest, with the id hx-target names (or the element's own, as htmx does).
func links(body string) []request {
	var rs []request
	for _, tag := range tagRe.FindAllString(body, -1) {
		attrs := map[string]string{}
		for _, m := range attrRe.FindAllStringSubmatch(tag, -1) {
			attrs[strings.ToLower(m[1])] = html.UnescapeString(m[2] + m[3])
		}
		if p, ok := localPath(attrs["href"]); ok {
			rs = append(rs, request{method: http.MethodGet, path: p})
		}
		if p, ok := localPath(attrs["action"]); ok {
			method := strings.ToUpper(attrs["method"])
			if method == "" {
				method = http.MethodGet
			}
			rs = append(rs, request{method: method, path: p})
		}
		target := attrs["hx-target"]
		if (target == "" || target == "this") && attrs["id"] != "" {
			target = "#" + attrs["id"]
		}
		for _, verb := range verbs {
			if p, ok := localPath(attrs["hx-"+verb]); ok {
				r := request{method: strings.ToUpper(verb), path: p, htmx: true}
				if id, ok := strings.CutPrefix(target, "#"); ok {
					r.target = id
				}
				rs = append(rs, r)
			}
		}
	}
	return rs
}

// localPath is u without its fragment, when it is a path on this app.
func localPath(u string) (string, bool) {
	u, _, _ = strings.Cut(u, "#")
	if !strings.HasPrefix(u, "/") || strings.HasPrefix(u, "//") {
		return "", false
	}
	return u, true
}

// compare checks got against file, or writes it there with -update.
func compare(t testing.TB, file string, got []byte) {
	t.Helper()
	if *update {
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(file, got, 0o644); err != nil { //nolint:gosec // a test fixture, readable like the source
			t.Fatal(err)
		}
		t.Logf("e2e: recorded %s", file)
		return
	}
	want, err := os.ReadFile(file)
	if err != nil {
		t.Fatalf("e2e: %v; record it from the dynamic build: go test -update", err)
	}
	if bytes.Equal(got, want) {
		return
	}
	// Report the first request whose response differs, and where.
	ws, gs := sections(want), sections(got)
	for i := 0; i < len(ws) || i < len(gs); i++ {
		w, g := at(ws, i), at(gs, i)
		if w == g {
			continue
		}
		req, _, _ := strings.Cut(cmp.Or(w, g), "\n")
		t.Errorf("e2e: response %d, to %s, differs from %s (the dynamic build's), first at %s",
			i+1, req, file, firstDiff(w, g))
		return
	}
}

// sections splits a recording into one string per request.
func sections(b []byte) []string {
	parts := strings.Split(string(b), "\n### ")
	return parts[1:] // parts[0] is the header
}

func at(ss []string, i int) string {
	if i < len(ss) {
		return ss[i]
	}
	return ""
}

// firstDiff says where want and got first differ, with a little of each
// around that point.
func firstDiff(want, got string) string {
	if want == "" {
		return "a request the dynamic build never made"
	}
	if got == "" {
		return "a request this build never made"
	}
	wl, gl := strings.Split(want, "\n"), strings.Split(got, "\n")
	for i := 0; ; i++ {
		a, b := at(wl, i), at(gl, i)
		if a == b {
			continue
		}
		c := 0
		for c < len(a) && c < len(b) && a[c] == b[c] {
			c++
		}
		return fmt.Sprintf("line %d, column %d:\n    want: %s\n    got:  %s", i+1, c+1, around(a, c), around(b, c))
	}
}

// around is s near byte c, cut at rune boundaries.
func around(s string, c int) string {
	lo, hi := max(0, c-40), min(len(s), c+60)
	for lo > 0 && !utf8.RuneStart(s[lo]) {
		lo--
	}
	for hi < len(s) && !utf8.RuneStart(s[hi]) {
		hi++
	}
	out := s[lo:hi]
	if lo > 0 {
		out = "…" + out
	}
	if hi < len(s) {
		out += "…"
	}
	return out
}
