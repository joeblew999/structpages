//go:build !tinygo && !structpages_static

package structpages

import (
	"reflect"
	"runtime"
)

// What structpages reads about functions and methods goes through these:
// here from reflect and the runtime, and under TinyGo, whose reflect can't
// list or call methods or read a function type's parameters, from the
// code structpages generate writes (methods_static.go).

func funcNumIn(t reflect.Type) int               { return t.NumIn() }
func funcIn(t reflect.Type, i int) reflect.Type  { return t.In(i) }
func funcNumOut(t reflect.Type) int              { return t.NumOut() }
func funcOut(t reflect.Type, i int) reflect.Type { return t.Out(i) }
func funcIsVariadic(t reflect.Type) bool         { return t.IsVariadic() }

// funcCall calls fn with in, as fn.Call does.
func funcCall(fn reflect.Value, in []reflect.Value) []reflect.Value { return fn.Call(in) }

// checkFuncType reports whether funcIn, funcOut and funcCall work for
// functions of type t. Reflect reads every function type.
func checkFuncType(reflect.Type) error { return nil }

// funcKey identifies fn's code: the same for every value of one function,
// method expression or method value, whatever its receiver.
func funcKey(fn reflect.Value) uintptr { return fn.Pointer() }

// funcName is the runtime's name for fn's code, such as
// "example.com/app.(*page).Content-fm", or "" when it has none.
func funcName(fn reflect.Value) string {
	f := runtime.FuncForPC(fn.Pointer())
	if f == nil {
		return ""
	}
	return f.Name()
}

// typeMethods lists t's exported methods, as t.Method does.
func typeMethods(t reflect.Type) ([]reflect.Method, error) {
	ms := make([]reflect.Method, t.NumMethod())
	for i := range ms {
		ms[i] = t.Method(i)
	}
	return ms, nil
}

// methodByName finds t's exported method name, as t.MethodByName does.
func methodByName(t reflect.Type, name string) (reflect.Method, bool) {
	return t.MethodByName(name)
}

// isPromotedMethod checks if a method is promoted from an embedded type.
// Promoted methods have an autogenerated wrapper that can be detected.
// See: https://github.com/golang/go/issues/73883
func isPromotedMethod(method *reflect.Method) bool {
	wPC := method.Func.Pointer()
	wFunc := runtime.FuncForPC(wPC)
	wFile, wLine := wFunc.FileLine(wPC)
	return wFile == "<autogenerated>" && wLine == 1
}
