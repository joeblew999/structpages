// Package tables holds what structpages reads about an app's functions and
// methods in builds whose reflect package can't: TinyGo's, which can't list
// or call a type's methods, read a function type's parameters and results,
// or name a function.
//
// structpages-gen writes a file into each package with pages that fills
// these tables at init, and structpages built with TinyGo (or with the
// structpages_tables build tag) reads them in place of reflect. Nothing here
// is meant to be written by hand; see the TinyGo page of the docs, and
// structpages' reflect_tables.go for when this package can go.
//
// Every Add function is for init functions: the tables are read without
// locking once the program runs.
package tables

import (
	"cmp"
	"reflect"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"
)

// FuncType is a function type: its parameters and results, and how to call
// a function of it.
type FuncType struct {
	Type     reflect.Type
	In, Out  []reflect.Type
	Variadic bool
	// Call calls fn, a function of Type, with in, as fn.Call(in) does.
	Call func(fn reflect.Value, in []reflect.Value) []reflect.Value
}

// Method is one of a type's methods. Unexported ones are only named, for a
// method expression passed to ID; Methods lists the exported ones, as
// reflect does.
type Method struct {
	Name string
	// Expr is the method expression, T.Name or (*T).Name; nil for a method
	// promoted from an embedded field, which structpages only finds by
	// name and never calls.
	Expr any
	// Bound is a method value, new(T).Name. Every method value of one
	// method shares its code, which is how structpages recognizes p.Name.
	Bound any
	// Promoted is what the runtime reports through its autogenerated
	// wrappers: true for a method promoted from an embedded field and, on
	// a pointer type, for a method declared on the value type
	// (golang/go#73883).
	Promoted bool
}

// Function is a package-level function, such as a standalone component.
type Function struct {
	Name string
	Func any
}

var (
	funcTypes = map[reflect.Type]*FuncType{}
	methods   = map[reflect.Type][]reflect.Method{}
	names     = map[uintptr]string{}
	promoted  = map[uintptr]bool{}
)

// AddFuncTypes adds function types. A type added again keeps its first
// entry: each package's file adds the types its own methods use.
func AddFuncTypes(fts ...FuncType) {
	for i := range fts {
		if _, ok := funcTypes[fts[i].Type]; !ok {
			funcTypes[fts[i].Type] = &fts[i]
		}
	}
}

// AddMethods adds t's methods: t is a named type or a pointer to one, and
// ms is its whole method set, with its own unexported methods.
func AddMethods(t reflect.Type, ms ...Method) {
	if _, ok := methods[t]; ok {
		return
	}
	recv, ptr := t, t.Kind() == reflect.Pointer
	if ptr {
		recv = t.Elem()
	}
	// The runtime names an instantiation's methods by its generic type, with
	// "[...]" for its type arguments: genericPage[...].Notes.
	name := recv.Name()
	if i := strings.IndexByte(name, '['); i >= 0 {
		name = name[:i] + "[...]"
	}
	prefix := pathToPrefix(recv.PkgPath()) + "."
	if ptr {
		prefix += "(*" + name + ")."
	} else {
		prefix += name + "."
	}
	rms := make([]reflect.Method, 0, len(ms))
	for _, m := range ms {
		exported := false
		if r, _ := utf8.DecodeRuneInString(m.Name); unicode.IsUpper(r) {
			exported = true
		}
		if m.Expr == nil {
			if exported {
				rms = append(rms, reflect.Method{Name: m.Name})
			}
			continue
		}
		fn := reflect.ValueOf(m.Expr)
		if exported {
			rms = append(rms, reflect.Method{Name: m.Name, Type: fn.Type(), Func: fn})
		}
		k := Key(fn)
		setName(k, prefix+m.Name)
		if m.Promoted {
			promoted[k] = true
		}
		if m.Bound != nil {
			setName(Key(reflect.ValueOf(m.Bound)), prefix+m.Name+"-fm")
		}
	}
	slices.SortFunc(rms, func(a, b reflect.Method) int { return cmp.Compare(a.Name, b.Name) })
	for i := range rms {
		rms[i].Index = i
	}
	methods[t] = rms
}

// AddFunctions adds package-level functions of the package with import
// path pkgPath ("main" for a command).
func AddFunctions(pkgPath string, fs ...Function) {
	prefix := pathToPrefix(pkgPath) + "."
	for _, f := range fs {
		setName(Key(reflect.ValueOf(f.Func)), prefix+f.Name)
	}
}

// setName names a function's code the first time it is seen. A method
// value's code can be shared, as with a method promoted from a type that
// is also a page; the first name stands.
func setName(k uintptr, name string) {
	if _, ok := names[k]; !ok {
		names[k] = name
	}
}

// LookupFuncType returns the function type t, if a table added it.
func LookupFuncType(t reflect.Type) (*FuncType, bool) {
	ft, ok := funcTypes[t]
	return ft, ok
}

// Methods returns t's exported methods sorted by name, as t.Method lists
// them, if a table added t.
func Methods(t reflect.Type) ([]reflect.Method, bool) {
	ms, ok := methods[t]
	return ms, ok
}

// MethodByName returns t's exported method name, as t.MethodByName does.
func MethodByName(t reflect.Type, name string) (reflect.Method, bool) {
	ms := methods[t]
	i, ok := slices.BinarySearchFunc(ms, name, func(m reflect.Method, name string) int {
		return strings.Compare(m.Name, name)
	})
	if !ok {
		return reflect.Method{}, false
	}
	return ms[i], true
}

// Name is the name the runtime gives fn's code, such as
// "example.com/app.(*page).Content-fm", or "" for a function no table
// added.
func Name(fn reflect.Value) string { return names[Key(fn)] }

// IsPromoted reports whether fn, the Func of a method from Methods, is one
// the runtime reaches through an autogenerated wrapper (see
// Method.Promoted). A promoted method listed without its expression has no
// Func, and is promoted.
func IsPromoted(fn reflect.Value) bool { return !fn.IsValid() || promoted[Key(fn)] }

// Arg converts v to T as fn.Call converts its arguments: v's type must be
// assignable to T.
func Arg[T any](v reflect.Value) T {
	var a T
	reflect.ValueOf(&a).Elem().Set(v)
	return a
}

// Result is r as fn.Call returns a result: a Value of r's declared type,
// even when that is an interface.
func Result[T any](r T) reflect.Value {
	return reflect.ValueOf(&r).Elem()
}

// pathToPrefix escapes an import path the way the runtime does in function
// names: control characters, '%' and '"' everywhere, and '.' after the
// last '/'.
func pathToPrefix(s string) string {
	slash := strings.LastIndex(s, "/")
	n := 0
	for r := 0; r < len(s); r++ {
		if c := s[r]; c <= ' ' || (c == '.' && r > slash) || c == '%' || c == '"' || c >= 0x7F {
			n++
		}
	}
	if n == 0 {
		return s
	}
	const hex = "0123456789abcdef"
	var b strings.Builder
	b.Grow(len(s) + 2*n)
	for r := 0; r < len(s); r++ {
		if c := s[r]; c <= ' ' || (c == '.' && r > slash) || c == '%' || c == '"' || c >= 0x7F {
			b.WriteByte('%')
			b.WriteByte(hex[c>>4])
			b.WriteByte(hex[c&0xF])
		} else {
			b.WriteByte(c)
		}
	}
	return b.String()
}
