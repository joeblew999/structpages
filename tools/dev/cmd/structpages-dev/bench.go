// benchFlags are every benchmark's, 6 runs of 200ms each: in-process with
// -benchmem; as served, times only (the allocations would be the client's).
var (
	benchFlags  = []string{"-run", "NoTest", "-bench", ".", "-count", "6", "-benchtime", "200ms"}
	benchmemArg = "-benchmem"
)

// bench is the bench command, one step: the current folder's benchmarks
// one way, in-process and, for an app, its build served, into build/bench/
// for report to compare.
func bench(args []string) int {
	if len(args) != 1 || !slices.Contains(ways, args[0]) {
		fmt.Fprintln(os.Stderr, "usage: structpages-dev bench dynamic|static|static-worker")
		return 2
	}
	if err := benchOne(newFolder("."), args[0]); err != nil {
		fmt.Fprintf(os.Stderr, "structpages-dev: %v\n", err)
		return 1
	}
	return 0
}

// benchWay runs f's benchmarks one way, in-process.
func benchWay(f folder, way string) (string, error) {
	args := append([]string{"test"}, benchFlags...)
	args = append(args, benchmemArg)
	tool := "go"
	switch way {
	case "static":
		args = append(args, "-tags", staticTag)
	case "static-worker":
		tool = "tinygo"
	}
	out, err := run(f.dir, tool, append(args, ".")...)
	if err != nil {
		return "", fmt.Errorf("%s benchmarks, %s: %w\n%s", f.name, way, err, failureLines(out))
	}
	if way == "static-worker" {
		// TinyGo prints 0 for every allocs/op: left out.
		out = regexp.MustCompile(`\s+0 allocs/op`).ReplaceAllString(out, "")
	}
	return out, nil
}

// benchstat compares the three ways' benchmark output, as the benchstat
// command does (mise installs it), and returns its tables.
func benchstat(outs map[string]string) (string, error) {
	dir, err := os.MkdirTemp("", "structpages-dev-bench-")
	if err != nil {
		return "", err
	}
	defer func() { _ = os.RemoveAll(dir) }()
	args := []string{"-ignore", "goos,goarch,pkg,cpu,/gomaxprocs"}
	for _, way := range ways {
		if _, ok := outs[way]; !ok {
			continue
		}
		file := filepath.Join(dir, way)
		if werr := os.WriteFile(file, []byte(outs[way]), 0o600); werr != nil {
			return "", werr
		}
		args = append(args, way+"="+file)
	}
	out, err := exec.Command("benchstat", args...).CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("benchstat: %w\n%s", err, out)
	}
	return strings.TrimRight(string(out), "\n"), nil
}

// wayDescriptions say what each way is, for BENCH_GENERATED.md.
var wayDescriptions = map[string]string{
	"dynamic":       "standard Go, structpages finding the app's methods at run time, with reflect",
	"static":        "standard Go, methods known at compile time from generated code (-tags structpages_static)",
	"static-worker": "a Cloudflare Worker, TinyGo WebAssembly, static too",
}

// writeBench writes f's BENCH_GENERATED.md, comparing the ways in present.
func writeBench(f folder, present []string, dynamic, inProcess, served, wasm string) error {
	file := filepath.Join(f.dir, "BENCH_GENERATED.md")
	task := "bench"
	if f.name != "library" {
		task = "example:" + f.name + ":bench"
	}
	cpu := ""
	if m := regexp.MustCompile(`(?m)^cpu: (.*)$`).FindStringSubmatch(dynamic); len(m) == 2 {
		cpu = ", " + m[1]
	}
	worker := ""
	if wasm != "" {
		worker = " (static-worker: " + wasm + " WebAssembly in workerd,\nwhat Cloudflare runs)"
	}
	var list strings.Builder
	for _, way := range present {
		fmt.Fprintf(&list, "- %s: %s\n", way, wayDescriptions[way])
	}
	count := map[int]string{1: "one way", 2: "two ways", 3: "three ways"}[len(present)]
	doc := fmt.Sprintf(`<!-- Generated by `+"`mise run %s`"+`. Do not edit: run it again. -->

# %s: benchmarks, %s

%s
%s
%s, %s%s, workerd %s.
6 runs of 200ms each.

## In-process

Each way's test binary calls the code directly (TinyGo's natively, and it reports no allocs/op).

`+"```"+`
%s
`+"```"+`

## As served

Each way served on :8080 as its example:%s:serve:<way> task serves it%s, timed over local HTTP
by one standard Go client, so every way pays the same network cost.

`+"```"+`
%s
`+"```"+`
`, task, f.name, count, list.String(), stamp(), version("go", "version"), version("tinygo", "version"), cpu,
		version("workerd", "--version"),
		inProcess, f.name, worker, served)
	if err := os.WriteFile(file, []byte(doc), 0o600); err != nil {
		return err
	}
	fmt.Println("wrote", file)
	return nil
}

// stamp is the commit the numbers are from, and whether anything but the
// BENCH_GENERATED.md files was changed from it: writing them would count.
func stamp() string {
	commit, _ := run(".", "git", "rev-parse", "--short", "HEAD")
	s := "Commit " + strings.TrimSpace(commit)
	// The whole repository, wherever it runs from.
	diff := exec.Command("git", "-C", root, "diff", "--quiet", "HEAD", "--", //nolint:gosec // git, on this repository
		".", ":(exclude,glob)**/BENCH_GENERATED.md")
	if err := diff.Run(); err != nil {
		s += " + uncommitted changes"
	}
	return s + ", " + time.Now().UTC().Format("2006-01-02T15:04Z") + "."
}

// version is the version a tool reports, as BENCH_GENERATED.md says it.
func version(tool, arg string) string {
	out, err := run(".", tool, arg)
	if err != nil {
		return "?"
	}
	fields := strings.Fields(out)
	switch tool {
	case "go": // go version go1.26.10 darwin/arm64
		if len(fields) >= 4 {
			return fields[2] + " " + fields[3]
		}
	case "tinygo": // tinygo version 0.43.0 darwin/arm64 (...)
		if len(fields) >= 4 {
			return fields[2] + " " + fields[3]
		}
	case "workerd": // workerd 2026-10-19
		if len(fields) >= 2 {
			return fields[1]
		}
	}
	return strings.TrimSpace(out)
}

// benchOne is bench's one step: f's benchmarks one way, in-process, into
// build/bench/<way>.txt, then, for an app, its build for the way served on
// addr and timed over local HTTP by one standard Go client (e2e.Bench with
// E2E_URL), so every way pays the same network cost, into
// build/bench/<way>-served.txt.
func benchOne(f folder, way string) error {
	dir := filepath.Join(f.dir, "build", "bench")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	fmt.Printf("%s, %s: in-process...\n", f.name, way)
	out, err := benchWay(f, way)
	if err != nil {
		return err
	}
	if werr := os.WriteFile(filepath.Join(dir, way+".txt"), []byte(out), 0o600); werr != nil {
		return werr
	}
	if f.name == "library" {
		return nil
	}
	fmt.Printf("%s, %s: served...\n", f.name, way)
	s, err := startBuild(f, way, nil)
	if err != nil {
		return err
	}
	defer s.stop()
	if werr := waitUp(s, time.Minute); werr != nil {
		return fmt.Errorf("%s, %s: %w", f.dir, way, werr)
	}
	args := append(append([]string{"test"}, benchFlags...), ".")
	cmd := exec.Command("go", args...) //nolint:gosec // the go toolchain, on the folder asked
	cmd.Dir = f.dir
	cmd.Env = append(os.Environ(), "E2E_URL=http://"+addr)
	served, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s, served %s: %w\n%s", f.dir, way, err, failureLines(string(served)))
	}
	return os.WriteFile(filepath.Join(dir, way+"-served.txt"), served, 0o600)
}

// report is the report command: the current folder's benchmark numbers, from
// its bench <way> steps, compared with benchstat into its BENCH_GENERATED.md.
func report(args []string) int {
	if len(args) != 0 {
		fmt.Fprintln(os.Stderr, "usage: structpages-dev report")
		return 2
	}
	f := newFolder(".")
	dir := filepath.Join(f.dir, "build", "bench")
	// The ways the folder has benchmark numbers for: all three, or fewer
	// for an example that can't build one (html-template has no
	// static-worker).
	var present []string
	for _, way := range ways {
		if fileExists(filepath.Join(dir, way+".txt")) {
			present = append(present, way)
		}
	}
	if len(present) == 0 {
		fail(fmt.Errorf("no benchmark numbers in %s: run its bench tasks first", dir))
	}
	read := func(suffix string) (map[string]string, error) {
		outs := map[string]string{}
		for _, way := range present {
			data, err := os.ReadFile(filepath.Join(dir, way+suffix))
			if err != nil {
				return nil, fmt.Errorf("%w: run bench %s first", err, way)
			}
			outs[way] = string(data)
		}
		return outs, nil
	}
	inProcess, err := read(".txt")
	if err != nil {
		fail(err)
	}
	table, err := benchstat(inProcess)
	if err != nil {
		fail(err)
	}
	served, wasm := "(the library is no app: nothing to serve)", ""
	if f.name != "library" {
		outs, rerr := read("-served.txt")
		if rerr != nil {
			fail(rerr)
		}
		if served, err = benchstat(outs); err != nil {
			fail(err)
		}
		if info, serr := os.Stat(filepath.Join(f.dir, "build", "static-worker", "app.wasm")); serr == nil {
			wasm = fmt.Sprintf("%d KB of", info.Size()/1024)
		}
	}
	if err := writeBench(f, present, inProcess["dynamic"], table, served, wasm); err != nil {
		fail(err)
	}
	return 0
}
