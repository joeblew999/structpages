// Command structpages-gen writes the tables structpages reads in builds
// whose reflect package can't list or call methods: TinyGo's.
//
//	go tool structpages-gen [-C dir] [-test] [-tags tags] [packages]
//
// For each package (default ./...) that declares page types, standalone
// components or request-arg functions, it writes
// structpages_tables.generated.go, built only under TinyGo or the
// structpages_tables build tag. With -test it also writes the tables for
// what the package's tests declare (structpages_tables.generated_test.go).
// Run it again whenever a page's methods change; a stale table fails at
// Mount.
// structpages' reflect_tables.go says why TinyGo needs this, and when it
// won't.
//
// -C runs it as if from dir, the way go -C does: packages load from there,
// for running it with go run from outside the module that has them.
package main

import (
	"bytes"
	"cmp"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	structpagesPath = "github.com/jackielii/structpages"
	tablesPath      = structpagesPath + "/tables"
	header          = "// Code generated by structpages-gen. DO NOT EDIT.\n"
	buildTag        = "//go:build tinygo || structpages_tables\n"
)

// pageMethods are the methods that make a struct a page on their own.
var pageMethods = []string{"Page", "ServeHTTP", "Middlewares", "RequestArgs", "Init"}

func main() {
	dir := flag.String("C", "", "change to `dir` before loading the packages")
	test := flag.Bool("test", false, "also write tables for what the packages' _test.go files declare")
	tags := flag.String("tags", "", "build tags to load the packages with")
	flag.Usage = func() {
		fmt.Fprintf(os.Stderr, "usage: structpages-gen [-C dir] [-test] [-tags tags] [packages]\n")
		flag.PrintDefaults()
	}
	flag.Parse()
	if *dir != "" {
		if err := os.Chdir(*dir); err != nil {
			fmt.Fprintln(os.Stderr, "structpages-gen:", err)
			os.Exit(2)
		}
	}
	patterns := flag.Args()
	if len(patterns) == 0 {
		patterns = []string{"./..."}
	}
	pkgs, err := load(patterns, *test, *tags)
	if err != nil {
		fmt.Fprintln(os.Stderr, "structpages-gen:", err)
		os.Exit(2)
	}
	if packages.PrintErrors(pkgs) > 0 {
		os.Exit(2)
	}
	routed := routedTypes(pkgs)
	failed := false
	for _, p := range pkgs {
		files, out := coveredFiles(p)
		if files == nil {
			continue
		}
		g := &gen{pkg: p, files: files, routed: routed, inTest: p.ID != p.PkgPath}
		src, err := g.generate()
		if err == nil {
			err = write(out, src)
		}
		if err != nil {
			fmt.Fprintf(os.Stderr, "structpages-gen: %s: %v\n", p.ID, err)
			failed = true
		}
	}
	if failed {
		os.Exit(1)
	}
}

func load(patterns []string, test bool, tags string) ([]*packages.Package, error) {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedDeps | packages.NeedImports,
		Tests: test,
		// Its own earlier output is left out: it may be stale.
		ParseFile: func(fset *token.FileSet, filename string, src []byte) (*ast.File, error) {
			mode := parser.AllErrors | parser.ParseComments
			if strings.HasPrefix(filepath.Base(filename), "structpages_tables") && bytes.Contains(src, []byte(header)) {
				mode = parser.PackageClauseOnly
			}
			return parser.ParseFile(fset, filename, src, mode)
		},
	}
	if tags != "" {
		cfg.BuildFlags = []string{"-tags=" + tags}
	}
	return packages.Load(cfg, patterns...)
}

// coveredFiles returns the files of p whose declarations p's table covers,
// and the table's path: a package's own files, its _test.go files in the
// package's test variant, and an external test package's files.
func coveredFiles(p *packages.Package) (files map[string]bool, out string) {
	if p.PkgPath == tablesPath || strings.HasSuffix(p.ID, ".test") || len(p.GoFiles) == 0 {
		return nil, ""
	}
	inTest := p.ID != p.PkgPath // "pkg [pkg.test]" or "pkg_test [pkg.test]"
	if p.PkgPath == structpagesPath && !inTest {
		return nil, "" // the library declares no pages; its tests do
	}
	files = map[string]bool{}
	for _, f := range p.GoFiles {
		if strings.HasSuffix(f, "_test.go") == inTest {
			files[f] = true
		}
	}
	if len(files) == 0 {
		return nil, ""
	}
	// The name says the file is generated; tests' tables still end in _test.go.
	name := "structpages_tables.generated.go"
	switch {
	case inTest && strings.HasSuffix(p.Name, "_test"):
		name = "structpages_tables_external.generated_test.go"
	case inTest:
		name = "structpages_tables.generated_test.go"
	}
	return files, filepath.Join(filepath.Dir(p.GoFiles[0]), name)
}

// routedTypes collects the named types of every route-tagged field in pkgs,
// by typeKey: pages, whatever else they declare. A package's test variant
// has its own type objects, so they are keyed by name.
func routedTypes(pkgs []*packages.Package) map[string]bool {
	routed := map[string]bool{}
	for _, p := range pkgs {
		for _, f := range p.Syntax {
			ast.Inspect(f, func(n ast.Node) bool {
				if st, ok := n.(*ast.StructType); ok {
					for _, field := range st.Fields.List {
						if field.Tag == nil || !hasRoute(field.Tag.Value) {
							continue
						}
						if tn := namedObj(p.TypesInfo.TypeOf(field.Type)); tn != nil && tn.Pkg() != nil {
							routed[typeKey(tn)] = true
						}
					}
				}
				return true
			})
		}
	}
	return routed
}

func hasRoute(lit string) bool {
	tag, err := strconv.Unquote(lit)
	if err != nil {
		return false
	}
	_, ok := reflect.StructTag(tag).Lookup("route")
	return ok
}

func typeKey(tn *types.TypeName) string { return tn.Pkg().Path() + "." + tn.Name() }

// namedObj is t's type name, through a pointer.
func namedObj(t types.Type) *types.TypeName {
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	if n, ok := t.(*types.Named); ok {
		return n.Origin().Obj()
	}
	return nil
}

type gen struct {
	pkg    *packages.Package
	files  map[string]bool
	routed map[string]bool
	inTest bool

	imports   map[string]string     // path → name
	names     map[string]bool       // names taken in the file
	funcTypes map[string]types.Type // *types.Signature, or a named function type
	generic   []*types.TypeName     // generic page types, whose instantiations get tables
	warnings  []string
}

func (g *gen) covered(pos token.Pos) bool {
	return g.files[g.pkg.Fset.Position(pos).Filename]
}

func (g *gen) warn(pos token.Pos, msg string, args ...any) {
	g.warnings = append(g.warnings, fmt.Sprintf("%s: %s", g.pkg.Fset.Position(pos), fmt.Sprintf(msg, args...)))
}

// pageType is one page type and its two method sets. typ is a named type
// declared in the package, or an instantiation of a generic one.
type pageType struct {
	typ            *types.Named
	value, pointer []method
}

type method struct {
	name     string
	sig      *types.Signature // with the receiver as its first parameter
	promoted bool             // reached through an autogenerated wrapper
	embedded bool             // promoted from an embedded field
}

func (g *gen) generate() ([]byte, error) {
	g.imports = map[string]string{}
	g.names = map[string]bool{}
	g.funcTypes = map[string]types.Type{}
	g.generic = nil
	for _, name := range g.pkg.Types.Scope().Names() {
		g.names[name] = true
	}
	var pages []pageType
	var funcs []*types.Func
	for _, f := range g.pkg.Syntax {
		if !g.covered(f.Pos()) {
			continue
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				pages = append(pages, g.pageTypes(d)...)
			case *ast.FuncDecl:
				if fn := g.funcDecl(d); fn != nil {
					funcs = append(funcs, fn)
				}
			}
		}
	}
	pages = append(pages, g.instantiations()...)
	// Request-arg functions used anywhere in the covered files: literals,
	// method values and functions from other packages, and values of a named
	// function type, which keep their name: that is the type reflect sees.
	for expr, tv := range g.pkg.TypesInfo.Types {
		if !g.covered(expr.Pos()) {
			continue
		}
		switch t := tv.Type.(type) {
		case *types.Signature:
			if isRequestArg(t) {
				g.addFuncType(t, expr.Pos())
			}
		case *types.Named:
			if sig, ok := t.Underlying().(*types.Signature); ok && isRequestArg(sig) {
				g.addNamedFuncType(t, expr.Pos())
			}
		}
	}
	for _, w := range g.warnings {
		fmt.Fprintln(os.Stderr, "structpages-gen: warning:", w)
	}
	if len(pages) == 0 && len(funcs) == 0 && len(g.funcTypes) == 0 {
		return nil, nil
	}
	return g.file(pages, funcs)
}

// pageTypes are the page types d declares.
func (g *gen) pageTypes(d *ast.GenDecl) []pageType {
	var pages []pageType
	for _, s := range d.Specs {
		ts, ok := s.(*ast.TypeSpec)
		if !ok || ts.Assign.IsValid() {
			continue
		}
		tn, _ := g.pkg.TypesInfo.Defs[ts.Name].(*types.TypeName)
		if tn == nil || !g.isPage(tn) {
			continue
		}
		if ts.TypeParams != nil {
			g.generic = append(g.generic, tn) // its instantiations get tables (instantiations)
			continue
		}
		if pt, ok := g.pageType(tn.Type().(*types.Named), tn.Pos()); ok {
			pages = append(pages, pt)
		}
	}
	return pages
}

// instantiations are the page types of the instantiations of g.generic the
// covered files use, such as genericPage[int] in a route: generated code can
// name a generic type's methods only with its type arguments. A generic page
// type used only inside generic code gets none, and a warning.
func (g *gen) instantiations() []pageType {
	if len(g.generic) == 0 {
		return nil
	}
	generic := map[*types.TypeName]bool{}
	for _, tn := range g.generic {
		generic[tn] = true
	}
	// Instances is a map: go through it in source order, so the file
	// comes out the same every time.
	ids := make([]*ast.Ident, 0, len(g.pkg.TypesInfo.Instances))
	for id := range g.pkg.TypesInfo.Instances {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i].Pos() < ids[j].Pos() })
	var pages []pageType
	seen, used := map[string]bool{}, map[*types.TypeName]bool{}
	for _, id := range ids {
		named, ok := g.pkg.TypesInfo.Instances[id].Type.(*types.Named)
		if !ok || !g.covered(id.Pos()) || !generic[named.Origin().Obj()] || g.unnameable(named) != "" {
			continue // a function, outside the files, another type, or inside generic code
		}
		used[named.Origin().Obj()] = true
		if key := types.TypeString(named, (*types.Package).Path); !seen[key] {
			seen[key] = true
			if pt, ok := g.pageType(named, named.Origin().Obj().Pos()); ok {
				pages = append(pages, pt)
			}
		}
	}
	for _, tn := range g.generic {
		if !used[tn] {
			g.warn(tn.Pos(), "generic type %s: no instantiation of it to write tables for", tn.Name())
		}
	}
	return pages
}

// funcDecl adds d's type when it is a request-arg provider, and returns it
// when it is a standalone component.
func (g *gen) funcDecl(d *ast.FuncDecl) *types.Func {
	fn, _ := g.pkg.TypesInfo.Defs[d.Name].(*types.Func)
	if fn == nil || d.Recv != nil || d.Type.TypeParams != nil {
		return nil
	}
	sig := fn.Type().(*types.Signature)
	if isRequestArg(sig) {
		g.addFuncType(sig, d.Pos())
	}
	if sig.Results().Len() == 1 && isComponent(sig.Results().At(0).Type()) {
		return fn
	}
	return nil
}

// isPage reports whether tn, a struct type declared in the package, is a
// page: it has route-tagged fields, is the type of one, or declares a page
// method or a component. Tests build pages in more ways, so in test files
// every struct type with methods counts.
func (g *gen) isPage(tn *types.TypeName) bool {
	if g.routed[typeKey(tn)] {
		return true
	}
	st, ok := tn.Type().Underlying().(*types.Struct)
	if !ok {
		return false
	}
	ms := types.NewMethodSet(types.NewPointer(tn.Type()))
	if g.inTest && ms.Len() > 0 {
		return true
	}
	for i := range st.NumFields() {
		if _, ok := reflect.StructTag(st.Tag(i)).Lookup("route"); ok {
			return true
		}
	}
	for i := range ms.Len() {
		fn := ms.At(i).Obj().(*types.Func)
		if !fn.Exported() {
			continue
		}
		if slices.Contains(pageMethods, fn.Name()) || strings.HasSuffix(fn.Name(), "Props") {
			return true
		}
		if sig := fn.Type().(*types.Signature); sig.Results().Len() == 1 && isComponent(sig.Results().At(0).Type()) {
			return true
		}
	}
	return false
}

// pageType lists t's methods on the value and the pointer type, as reflect
// would, and adds their function types; pos is where a warning points.
func (g *gen) pageType(t *types.Named, pos token.Pos) (pageType, bool) {
	value, ok := g.methods(t, false, pos)
	if !ok {
		return pageType{}, false
	}
	pointer, ok := g.methods(t, true, pos)
	if !ok {
		return pageType{}, false
	}
	return pageType{typ: t, value: value, pointer: pointer}, true
}

// methods lists the method set of t, or of *t, sorted by name. Its own
// unexported methods are listed too: reflect doesn't list them, but ID and
// RenderTarget.Is name them when a method expression is passed.
func (g *gen) methods(t *types.Named, ptr bool, pos token.Pos) ([]method, bool) {
	var recv types.Type = t
	if ptr {
		recv = types.NewPointer(recv)
	}
	ms := types.NewMethodSet(recv)
	list := make([]method, 0, ms.Len())
	for i := range ms.Len() {
		sel := ms.At(i)
		fn := sel.Obj().(*types.Func)
		embedded := len(sel.Index()) > 1
		if !fn.Exported() && (embedded || fn.Pkg() != g.pkg.Types) {
			continue
		}
		sig := fn.Type().(*types.Signature)
		_, ptrRecv := sig.Recv().Type().(*types.Pointer)
		m := method{
			name:     fn.Name(),
			sig:      withReceiver(recv, sig),
			embedded: embedded,
			// Through the pointer type, a method declared on the value
			// type is an autogenerated wrapper too.
			promoted: embedded || (ptr && !ptrRecv),
		}
		// structpages never calls a promoted method: it is listed by name.
		if !embedded {
			if why := g.unnameable(m.sig); why != "" {
				g.warn(pos, "page type %s: method %s: %s", types.TypeString(t, nil), fn.Name(), why)
				return nil, false
			}
			g.addFuncType(m.sig, pos)
		}
		list = append(list, m)
	}
	sort.Slice(list, func(i, j int) bool { return list[i].name < list[j].name })
	return list, true
}

// withReceiver is sig with recv as its first parameter: a method
// expression's type.
func withReceiver(recv types.Type, sig *types.Signature) *types.Signature {
	params := make([]*types.Var, 0, 1+sig.Params().Len())
	params = append(params, types.NewParam(token.NoPos, nil, "", recv))
	for i := range sig.Params().Len() {
		params = append(params, types.NewParam(token.NoPos, nil, "", sig.Params().At(i).Type()))
	}
	return types.NewSignatureType(nil, nil, nil, types.NewTuple(params...), unnamed(sig.Results()), sig.Variadic())
}

func unnamed(t *types.Tuple) *types.Tuple {
	vs := make([]*types.Var, t.Len())
	for i := range vs {
		vs[i] = types.NewParam(token.NoPos, nil, "", t.At(i).Type())
	}
	return types.NewTuple(vs...)
}

func (g *gen) addFuncType(sig *types.Signature, pos token.Pos) {
	sig = types.NewSignatureType(nil, nil, nil, unnamed(sig.Params()), unnamed(sig.Results()), sig.Variadic())
	if why := g.unnameable(sig); why != "" {
		g.warn(pos, "function type %s: %s", types.TypeString(sig, nil), why)
		return
	}
	g.funcTypes[types.TypeString(sig, (*types.Package).Path)] = sig
}

// addNamedFuncType adds t, a named function type, under its own name.
func (g *gen) addNamedFuncType(t *types.Named, pos token.Pos) {
	if why := g.unnameable(t); why != "" {
		g.warn(pos, "function type %s: %s", t.Obj().Name(), why)
		return
	}
	g.funcTypes[types.TypeString(t, (*types.Package).Path)] = t
}

// unnameable says why t can't be written in the generated file, or "".
func (g *gen) unnameable(t types.Type) string {
	switch t := t.(type) {
	case *types.Basic:
		return ""
	case *types.Named:
		return g.unnameableNamed(t)
	case *types.Alias:
		return g.unnameable(types.Unalias(t))
	case *types.TypeParam:
		return "it uses type parameter " + t.Obj().Name()
	case *types.Pointer:
		return g.unnameable(t.Elem())
	case *types.Slice:
		return g.unnameable(t.Elem())
	case *types.Array:
		return g.unnameable(t.Elem())
	case *types.Chan:
		return g.unnameable(t.Elem())
	case *types.Map:
		return cmp.Or(g.unnameable(t.Key()), g.unnameable(t.Elem()))
	case *types.Signature:
		return cmp.Or(g.unnameableTuple(t.Params()), g.unnameableTuple(t.Results()))
	case *types.Struct:
		return g.unnameableStruct(t)
	case *types.Interface:
		return g.unnameableInterface(t)
	}
	return fmt.Sprintf("unsupported type %s", t)
}

func (g *gen) unnameableNamed(t *types.Named) string {
	obj := t.Obj()
	if obj.Pkg() != nil {
		if obj.Parent() != obj.Pkg().Scope() {
			return obj.Name() + " is declared inside a function"
		}
		if obj.Pkg() != g.pkg.Types && obj.Pkg().Path() != g.pkg.PkgPath && !obj.Exported() {
			return obj.Name() + " is unexported in " + obj.Pkg().Path()
		}
	}
	if t.TypeParams().Len() > 0 && t.TypeArgs().Len() == 0 {
		return obj.Name() + " is generic"
	}
	for i := range t.TypeArgs().Len() {
		if why := g.unnameable(t.TypeArgs().At(i)); why != "" {
			return why
		}
	}
	return ""
}

func (g *gen) unnameableTuple(t *types.Tuple) string {
	for i := range t.Len() {
		if why := g.unnameable(t.At(i).Type()); why != "" {
			return why
		}
	}
	return ""
}

func (g *gen) unnameableStruct(t *types.Struct) string {
	for i := range t.NumFields() {
		f := t.Field(i)
		if !f.Exported() && f.Pkg() != g.pkg.Types {
			return "a struct type with unexported fields of another package"
		}
		if why := g.unnameable(f.Type()); why != "" {
			return why
		}
	}
	return ""
}

func (g *gen) unnameableInterface(t *types.Interface) string {
	for i := range t.NumExplicitMethods() {
		m := t.ExplicitMethod(i)
		if !m.Exported() && m.Pkg() != g.pkg.Types {
			return "an interface type with unexported methods of another package"
		}
		if why := g.unnameable(m.Type()); why != "" {
			return why
		}
	}
	for i := range t.NumEmbeddeds() {
		if why := g.unnameable(t.EmbeddedType(i)); why != "" {
			return why
		}
	}
	return ""
}

// isComponent reports whether t has Render(context.Context, io.Writer) error.
func isComponent(t types.Type) bool {
	obj, _, _ := types.LookupFieldOrMethod(t, true, nil, "Render")
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig := fn.Type().(*types.Signature)
	return sig.Params().Len() == 2 && sig.Results().Len() == 1 &&
		types.TypeString(sig.Params().At(0).Type(), nil) == "context.Context" &&
		types.TypeString(sig.Params().At(1).Type(), nil) == "io.Writer" &&
		types.TypeString(sig.Results().At(0).Type(), nil) == "error"
}

// isRequestArg reports whether sig is a request-arg provider's:
// func(*http.Request) (T, error) or func(*http.Request, *PageNode) (T, error).
func isRequestArg(sig *types.Signature) bool {
	if sig.TypeParams().Len() > 0 || sig.Variadic() || sig.Results().Len() != 2 ||
		types.TypeString(sig.Results().At(1).Type(), nil) != "error" {
		return false
	}
	ps := sig.Params()
	if ps.Len() != 1 && ps.Len() != 2 {
		return false
	}
	if types.TypeString(ps.At(0).Type(), nil) != "*net/http.Request" {
		return false
	}
	return ps.Len() == 1 || types.TypeString(ps.At(1).Type(), nil) == "*"+structpagesPath+".PageNode"
}

// qualifier names other packages' types by their imports in the generated
// file.
func (g *gen) qualifier(p *types.Package) string {
	if p == g.pkg.Types || p.Path() == g.pkg.PkgPath {
		return ""
	}
	return g.importName(p.Path(), p.Name())
}

func (g *gen) importName(path, name string) string {
	if n, ok := g.imports[path]; ok {
		return n
	}
	n := name
	for i := 2; g.names[n]; i++ {
		n = name + strconv.Itoa(i)
	}
	g.names[n] = true
	g.imports[path] = n
	return n
}

func (g *gen) typ(t types.Type) string { return types.TypeString(t, g.qualifier) }

// writer writes the generated file's init function.
type writer struct {
	g                       *gen
	buf                     bytes.Buffer
	reflectName, tablesName string
}

func (w *writer) printf(msg string, args ...any) { fmt.Fprintf(&w.buf, msg, args...) }

func (g *gen) file(pages []pageType, funcs []*types.Func) ([]byte, error) {
	w := &writer{g: g}
	// reflect is used by function types and method tables only: a package
	// with nothing but standalone component functions doesn't import it.
	if len(g.funcTypes) > 0 || len(pages) > 0 {
		w.reflectName = g.importName("reflect", "reflect")
	}
	w.tablesName = g.importName(tablesPath, "tables")
	w.printf("func init() {\n")
	w.writeFuncTypes()
	sort.Slice(pages, func(i, j int) bool { return g.typ(pages[i].typ) < g.typ(pages[j].typ) })
	for _, pt := range pages {
		w.writeMethods(pt, false)
		w.writeMethods(pt, true)
	}
	w.writeFunctions(funcs)
	w.printf("}\n")

	var out bytes.Buffer
	out.WriteString(buildTag + "\n" + header + "\npackage " + g.pkg.Name + "\n\n")
	g.writeImports(&out)
	out.Write(w.buf.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the generated file: %w\n%s", err, out.Bytes())
	}
	return src, nil
}

// writeImports writes the import block: the standard library, then the
// rest.
func (g *gen) writeImports(out *bytes.Buffer) {
	var std, others []string
	for p := range g.imports {
		if strings.Contains(strings.Split(p, "/")[0], ".") {
			others = append(others, p)
		} else {
			std = append(std, p)
		}
	}
	sort.Strings(std)
	sort.Strings(others)
	out.WriteString("import (\n")
	for i, group := range [][]string{std, others} {
		if i > 0 && len(std) > 0 && len(others) > 0 {
			out.WriteString("\n")
		}
		for _, p := range group {
			if n := g.imports[p]; n != filepath.Base(p) {
				fmt.Fprintf(out, "%s %q\n", n, p)
			} else {
				fmt.Fprintf(out, "%q\n", p)
			}
		}
	}
	out.WriteString(")\n\n")
}

func (w *writer) writeFuncTypes() {
	if len(w.g.funcTypes) == 0 {
		return
	}
	keys := make([]string, 0, len(w.g.funcTypes))
	for k := range w.g.funcTypes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	w.printf("%s.AddFuncTypes(\n", w.tablesName)
	for _, k := range keys {
		w.writeFuncType(w.g.funcTypes[k])
	}
	w.printf(")\n")
}

// writeFuncType writes the table of t, a function type or a named one: its
// types and a call that converts the arguments and results as
// reflect.Value.Call does.
func (w *writer) writeFuncType(t types.Type) {
	sig := t.Underlying().(*types.Signature)
	ft := w.g.typ(t)
	params, results := sig.Params(), sig.Results()
	w.printf("%s.FuncType{\n", w.tablesName)
	w.printf("Type: %s.TypeFor[%s](),\n", w.reflectName, ft)
	w.printf("In: []%s.Type{%s},\n", w.reflectName, w.typeList(params))
	w.printf("Out: []%s.Type{%s},\n", w.reflectName, w.typeList(results))
	if sig.Variadic() {
		w.printf("Variadic: true,\n")
	}
	w.printf("Call: func(fn %s.Value, in []%s.Value) []%s.Value {\n", w.reflectName, w.reflectName, w.reflectName)
	n := params.Len()
	args := make([]string, 0, n)
	for i := range n {
		pt := params.At(i).Type()
		if sig.Variadic() && i == n-1 {
			elem := w.g.typ(pt.(*types.Slice).Elem())
			w.printf("rest := make([]%s, len(in)-%d)\n", elem, n-1)
			w.printf("for i, v := range in[%d:] {\nrest[i] = %s.Arg[%s](v)\n}\n", n-1, w.tablesName, elem)
			args = append(args, "rest...")
			continue
		}
		args = append(args, fmt.Sprintf("%s.Arg[%s](in[%d])", w.tablesName, w.g.typ(pt), i))
	}
	call := fmt.Sprintf("fn.Interface().(%s)(%s)", ft, strings.Join(args, ", "))
	if results.Len() == 0 {
		w.printf("%s\nreturn nil\n", call)
	} else {
		rs := make([]string, results.Len())
		vs := make([]string, results.Len())
		for i := range rs {
			rs[i] = "r" + strconv.Itoa(i)
			vs[i] = fmt.Sprintf("%s.Result(r%d)", w.tablesName, i)
		}
		w.printf("%s := %s\n", strings.Join(rs, ", "), call)
		w.printf("return []%s.Value{%s}\n", w.reflectName, strings.Join(vs, ", "))
	}
	w.printf("},\n},\n")
}

func (w *writer) typeList(t *types.Tuple) string {
	ts := make([]string, t.Len())
	for i := range ts {
		ts[i] = fmt.Sprintf("%s.TypeFor[%s]()", w.reflectName, w.g.typ(t.At(i).Type()))
	}
	return strings.Join(ts, ", ")
}

// writeMethods writes the method set of pt's type, or of a pointer to it.
func (w *writer) writeMethods(pt pageType, ptr bool) {
	typ := w.g.typ(pt.typ) // page, or genericPage[int]
	list, recv := pt.value, typ
	if ptr {
		list, recv = pt.pointer, "*"+typ
	}
	if len(list) == 0 {
		return
	}
	w.printf("%s.AddMethods(%s.TypeFor[%s](),\n", w.tablesName, w.reflectName, recv)
	for _, m := range list {
		if m.embedded {
			// structpages only skips a promoted method or finds it by
			// name. Its expression could name a method TinyGo's own
			// standard library lacks (testing.TB's, say).
			w.printf("%s.Method{Name: %q, Promoted: true},\n", w.tablesName, m.name)
			continue
		}
		expr := recv + "." + m.name
		if ptr {
			expr = "(" + recv + ")." + m.name
		}
		w.printf("%s.Method{Name: %q, Expr: %s, Bound: new(%s).%s", w.tablesName, m.name, expr, typ, m.name)
		if m.promoted {
			w.printf(", Promoted: true")
		}
		w.printf("},\n")
	}
	w.printf(")\n")
}

// writeFunctions writes the package's standalone components, named as the
// runtime names them: by import path, "main" for a command.
func (w *writer) writeFunctions(funcs []*types.Func) {
	if len(funcs) == 0 {
		return
	}
	sort.Slice(funcs, func(i, j int) bool { return funcs[i].Name() < funcs[j].Name() })
	path := w.g.pkg.PkgPath
	if w.g.pkg.Name == "main" {
		path = "main"
	}
	w.printf("%s.AddFunctions(%q,\n", w.tablesName, path)
	for _, fn := range funcs {
		w.printf("%s.Function{Name: %q, Func: %s},\n", w.tablesName, fn.Name(), fn.Name())
	}
	w.printf(")\n")
}

// write writes src to path, or removes a generated file there when src is
// nil. It leaves a file it didn't write alone.
func write(path string, src []byte) error {
	old, err := os.ReadFile(path)
	if err == nil && !bytes.Contains(old, []byte(header)) {
		if src == nil {
			return nil
		}
		return fmt.Errorf("%s exists and was not written by structpages-gen", path)
	}
	if src == nil {
		if err == nil {
			return os.Remove(path)
		}
		return nil
	}
	if bytes.Equal(old, src) {
		return nil
	}
	return os.WriteFile(path, src, 0o644) //nolint:gosec // source code, readable like any other
}
